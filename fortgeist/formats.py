"""Session file formats.

While recording, everything goes into append-only binary files with fixed-size
records (`*.bin`). A crash loses at most the unfinished tail (it is
discarded on read). At finalization the `.bin` files are converted to Parquet.
"""

from __future__ import annotations

import json
import os
import struct
from pathlib import Path
from typing import Any

import numpy as np

# ---------------------------------------------------------------- input events
DEVICE_MOUSE = 1
DEVICE_KEYBOARD = 2
DEVICE_NAMES = {DEVICE_MOUSE: "mouse", DEVICE_KEYBOARD: "keyboard"}

KIND_MOVE = 1
KIND_BUTTON = 2
KIND_WHEEL = 3
KIND_KEY = 4
KIND_NAMES = {KIND_MOVE: "move", KIND_BUTTON: "button", KIND_WHEEL: "wheel", KIND_KEY: "key"}

# mouse button codes (code field when kind=button)
MOUSE_LEFT, MOUSE_RIGHT, MOUSE_MIDDLE, MOUSE_X1, MOUSE_X2 = 1, 2, 3, 4, 5
MOUSE_BUTTON_NAMES = {1: "LMB", 2: "RMB", 3: "MMB", 4: "X1", 5: "X2"}
# wheel codes (code field when kind=wheel)
WHEEL_VERTICAL, WHEEL_HORIZONTAL = 0, 1

# flags field bits
FLAG_KEY_E0 = 0x01
FLAG_KEY_E1 = 0x02
FLAG_MOUSE_ABSOLUTE = 0x04
FLAG_MOUSE_VIRTUAL_DESKTOP = 0x08
FLAG_SYNTHETIC = 0x10  # generated by the recorder (release on pause / press on resume)
FLAG_INJECTED = 0x20  # hDevice == NULL: synthesized input (SendInput etc.)

STATE_NA = -1  # for move/wheel

INPUT_STRUCT = struct.Struct("<qBBbxHxxiiiii")  # 36 bytes
INPUT_DTYPE = np.dtype(
    {
        "names": ["t_ns", "device", "kind", "state", "flags", "code", "vk", "dx", "dy", "wheel"],
        "formats": ["<i8", "u1", "u1", "i1", "<u2", "<i4", "<i4", "<i4", "<i4", "<i4"],
        "offsets": [0, 8, 9, 10, 12, 16, 20, 24, 28, 32],
        "itemsize": 36,
    }
)
assert INPUT_STRUCT.size == INPUT_DTYPE.itemsize

# ---------------------------------------------------------------- frames
# frame_idx, t_ns, t_present_ns, dropped_before, accumulated_frames, is_new
FRAME_STRUCT = struct.Struct("<qqqiib7x")  # 40 bytes
FRAME_DTYPE = np.dtype(
    {
        "names": ["frame_idx", "t_ns", "t_present_ns", "dropped_before", "accumulated_frames", "is_new"],
        "formats": ["<i8", "<i8", "<i8", "<i4", "<i4", "i1"],
        "offsets": [0, 8, 16, 24, 28, 32],
        "itemsize": 40,
    }
)
assert FRAME_STRUCT.size == FRAME_DTYPE.itemsize

# architecture B: raw showinfo lines -> (n, pts_us, arrival_ns)
FRAME_B_STRUCT = struct.Struct("<qqq")
FRAME_B_DTYPE = np.dtype([("n", "<i8"), ("pts_us", "<i8"), ("arrival_ns", "<i8")])

# ---------------------------------------------------------------- file names
INPUTS_BIN = "inputs.bin"
INPUTS_PARQUET = "inputs.parquet"
META_JSON = "meta.json"
MARKERS_JSONL = "markers.jsonl"
FOCUS_JSONL = "focus.jsonl"
RECORDER_LOG = "recorder.log"
GAME_SETTINGS_JSON = "game_settings.json"


def chunk_video(idx: int) -> str:
    return f"chunk_{idx:03d}.mkv"


def chunk_frames_bin(idx: int) -> str:
    return f"chunk_{idx:03d}.frames.bin"


def chunk_frames_b_bin(idx: int) -> str:
    return f"chunk_{idx:03d}.framesB.bin"


def chunk_frames_parquet(idx: int) -> str:
    return f"chunk_{idx:03d}.frames.parquet"


def read_bin(path: Path, dtype: np.dtype) -> np.ndarray:
    """Reads an append-only record file, discarding the unfinished tail."""
    if not path.exists():
        return np.zeros(0, dtype=dtype)
    raw = path.read_bytes()
    n = len(raw) // dtype.itemsize
    return np.frombuffer(raw[: n * dtype.itemsize], dtype=dtype).copy()


class AppendFile:
    """Thin wrapper over os.write: no Python buffer, data goes straight to the OS."""

    def __init__(self, path: Path):
        self.path = path
        flags = os.O_WRONLY | os.O_CREAT | os.O_APPEND | getattr(os, "O_BINARY", 0)
        self.fd = os.open(path, flags, 0o644)

    def write(self, data: bytes | bytearray | memoryview) -> None:
        mv = memoryview(data)
        while mv:
            n = os.write(self.fd, mv)
            mv = mv[n:]

    def fsync(self) -> None:
        try:
            os.fsync(self.fd)
        except OSError:
            pass

    def close(self) -> None:
        if self.fd >= 0:
            self.fsync()
            os.close(self.fd)
            self.fd = -1


class JsonlWriter:
    def __init__(self, path: Path):
        self.f = AppendFile(path)

    def write(self, obj: dict[str, Any]) -> None:
        self.f.write((json.dumps(obj, ensure_ascii=False) + "\n").encode("utf-8"))

    def close(self) -> None:
        self.f.close()


def read_jsonl(path: Path) -> list[dict[str, Any]]:
    out: list[dict[str, Any]] = []
    if not path.exists():
        return out
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line:
            continue
        try:
            out.append(json.loads(line))
        except json.JSONDecodeError:
            # unfinished last line after a crash
            continue
    return out


# ---------------------------------------------------------------- parquet
def inputs_to_table(arr: np.ndarray):
    import pyarrow as pa

    dev = pa.DictionaryArray.from_arrays(
        pa.array(_map_codes(arr["device"], {1: 0, 2: 1}), pa.int8()),
        pa.array(["mouse", "keyboard"]),
    )
    kind = pa.DictionaryArray.from_arrays(
        pa.array(_map_codes(arr["kind"], {1: 0, 2: 1, 3: 2, 4: 3}), pa.int8()),
        pa.array(["move", "button", "wheel", "key"]),
    )
    return pa.table(
        {
            "t_ns": pa.array(arr["t_ns"], pa.int64()),
            "device": dev,
            "kind": kind,
            "code": pa.array(arr["code"], pa.int32()),
            "vk": pa.array(arr["vk"], pa.int32()),
            "state": pa.array(arr["state"], pa.int8()),
            "dx": pa.array(arr["dx"], pa.int32()),
            "dy": pa.array(arr["dy"], pa.int32()),
            "wheel": pa.array(arr["wheel"], pa.int32()),
            "flags": pa.array(arr["flags"].astype(np.int16), pa.int16()),
        }
    )


def _map_codes(values: np.ndarray, mapping: dict[int, int]) -> np.ndarray:
    out = np.full(values.shape, -1, dtype=np.int8)
    for k, v in mapping.items():
        out[values == k] = v
    if (out < 0).any():
        raise ValueError("unknown device/kind code in inputs.bin")
    return out


def frames_to_table(arr: np.ndarray):
    import pyarrow as pa

    return pa.table(
        {
            "frame_idx": pa.array(arr["frame_idx"], pa.int64()),
            "t_ns": pa.array(arr["t_ns"], pa.int64()),
            "dropped_before": pa.array(arr["dropped_before"], pa.int32()),
            "t_present_ns": pa.array(arr["t_present_ns"], pa.int64()),
            "is_new": pa.array(arr["is_new"], pa.int8()),
            "accumulated_frames": pa.array(arr["accumulated_frames"], pa.int32()),
        }
    )


def write_parquet(table, path: Path) -> None:
    import pyarrow.parquet as pq

    tmp = path.with_suffix(path.suffix + ".tmp")
    pq.write_table(table, tmp, compression="zstd")
    os.replace(tmp, path)


def load_inputs(session_dir: Path) -> np.ndarray:
    """inputs as a numpy INPUT_DTYPE array, from parquet or (if not finalized) from .bin."""
    pq_path = session_dir / INPUTS_PARQUET
    if pq_path.exists():
        import pyarrow.parquet as pq

        t = pq.read_table(pq_path)
        n = t.num_rows
        out = np.zeros(n, dtype=INPUT_DTYPE)
        for name in ("t_ns", "code", "vk", "state", "dx", "dy", "wheel", "flags"):
            out[name] = t.column(name).to_numpy()
        dev = np.asarray(t.column("device").to_pylist(), dtype=object) if n else np.array([], object)
        kind = np.asarray(t.column("kind").to_pylist(), dtype=object) if n else np.array([], object)
        out["device"] = np.where(dev == "mouse", DEVICE_MOUSE, DEVICE_KEYBOARD)
        km = {"move": KIND_MOVE, "button": KIND_BUTTON, "wheel": KIND_WHEEL, "key": KIND_KEY}
        out["kind"] = np.array([km[k] for k in kind], dtype=np.uint8) if n else out["kind"]
        return out
    return read_bin(session_dir / INPUTS_BIN, INPUT_DTYPE)


def load_frames(session_dir: Path, idx: int) -> np.ndarray:
    pq_path = session_dir / chunk_frames_parquet(idx)
    if pq_path.exists():
        import pyarrow.parquet as pq

        t = pq.read_table(pq_path)
        out = np.zeros(t.num_rows, dtype=FRAME_DTYPE)
        for name in FRAME_DTYPE.names:
            out[name] = t.column(name).to_numpy()
        return out
    return read_bin(session_dir / chunk_frames_bin(idx), FRAME_DTYPE)


def list_chunks(session_dir: Path) -> list[int]:
    idx = set()
    for p in session_dir.glob("chunk_*.mkv"):
        try:
            idx.add(int(p.name[6:9]))
        except ValueError:
            pass
    return sorted(idx)
